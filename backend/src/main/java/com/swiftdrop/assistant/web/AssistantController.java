package com.swiftdrop.assistant.web;

import org.springframework.http.HttpStatus;
import org.springframework.security.access.prepost.PreAuthorize;
import org.springframework.web.bind.annotation.PostMapping;
import org.springframework.web.bind.annotation.RequestBody;
import org.springframework.web.bind.annotation.RequestMapping;
import org.springframework.web.bind.annotation.ResponseStatus;
import org.springframework.web.bind.annotation.RestController;

import com.swiftdrop.assistant.application.AssistantService;

import jakarta.validation.Valid;

/**
 * AI delivery assistant chat endpoint (CUS bonus). Any signed-in customer may ask questions;
 * answers are generated by Gemini using live parcel tracking and pricing data.
 */
@RestController
@RequestMapping("/api/v1/assistant")
class AssistantController {

    private final AssistantService assistant;

    AssistantController(AssistantService assistant) {
        this.assistant = assistant;
    }

    @PostMapping("/chat")
    @PreAuthorize("hasRole('CUSTOMER')")
    @ResponseStatus(HttpStatus.OK)
    ChatResponse chat(@Valid @RequestBody ChatRequest request) {
        return new ChatResponse(assistant.chat(request.message()));
    }
}
